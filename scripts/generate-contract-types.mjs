import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = dirname(scriptDirectory);
const schemaPaths = [
  join(repositoryRoot, "shared/contracts/schemas/kairo-answer.v1.json"),
  join(repositoryRoot, "shared/contracts/schemas/core-command.v1.json")
];
const outputPath = join(
  repositoryRoot,
  "shared/contracts/generated/contracts.v1.ts"
);

function referenceName(reference) {
  return reference.slice(reference.lastIndexOf("/") + 1);
}

function objectTypeExpression(schema) {
  const required = new Set(schema.required ?? []);
  const properties = Object.entries(schema.properties ?? {}).map(
    ([propertyName, propertySchema]) => {
      const optional = required.has(propertyName) ? "" : "?";
      return `${propertyName}${optional}: ${typeExpression(propertySchema)};`;
    }
  );

  return `{ ${properties.join(" ")} }`;
}

function typeExpression(schema) {
  if (schema.$ref) {
    return referenceName(schema.$ref);
  }

  if (schema.const !== undefined) {
    return JSON.stringify(schema.const);
  }

  if (schema.enum) {
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  }

  if (schema.type === "array") {
    return `Array<${typeExpression(schema.items)}>`;
  }

  if (schema.type === "object") {
    return schema.properties
      ? objectTypeExpression(schema)
      : "Record<string, unknown>";
  }

  if (schema.type === "integer" || schema.type === "number") {
    return "number";
  }

  if (schema.type === "boolean") {
    return "boolean";
  }

  return "string";
}

function withEnvelopeProperties(schema, branch) {
  const properties = {
    ...(schema.properties ?? {}),
    ...(branch.properties ?? {})
  };

  for (const propertyName of branch.not?.required ?? []) {
    delete properties[propertyName];
  }

  return {
    type: schema.type,
    required: [...new Set([...(schema.required ?? []), ...(branch.required ?? [])])],
    properties
  };
}

function renderUnion(name, schema) {
  const members = schema.oneOf.map((branch) =>
    objectTypeExpression(withEnvelopeProperties(schema, branch))
  );

  return `export type ${name} =\n${members
    .map((member) => `  | ${member}`)
    .join("\n")};`;
}

function renderObject(name, schema) {
  const required = new Set(schema.required ?? []);
  const lines = [`export interface ${name} {`];

  for (const [propertyName, propertySchema] of Object.entries(
    schema.properties ?? {}
  )) {
    const optional = required.has(propertyName) ? "" : "?";
    lines.push(
      `  ${propertyName}${optional}: ${typeExpression(propertySchema)};`
    );
  }

  lines.push("}");
  return lines.join("\n");
}

function renderNamedSchema(name, schema) {
  if (schema.oneOf) {
    return renderUnion(name, schema);
  }

  if (schema.type === "object") {
    return renderObject(name, schema);
  }

  return `export type ${name} = ${typeExpression(schema)};`;
}

function generatedContents() {
  const schemas = schemaPaths.map((schemaPath) =>
    JSON.parse(readFileSync(schemaPath, "utf8"))
  );
  const declarations = [
    "// This file is generated by scripts/generate-contract-types.mjs. Do not edit."
  ];

  for (const schema of schemas) {
    if (schema.title === "KairoAnswerV1") {
      declarations.push(renderNamedSchema(schema.title, schema));
    }

    for (const [name, definition] of Object.entries(schema.$defs ?? {})) {
      declarations.push(renderNamedSchema(name, definition));
    }
  }

  return `${declarations.join("\n\n")}\n`;
}

export function generateContractTypes({ check = false } = {}) {
  const expected = generatedContents();
  let current = "";

  try {
    current = readFileSync(outputPath, "utf8");
  } catch {
    current = "";
  }

  if (check) {
    return { clean: current === expected };
  }

  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, expected);
  return { clean: true };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = generateContractTypes({ check: process.argv.includes("--check") });

  if (result.clean) {
    console.log("Contract TypeScript declarations are current.");
  } else {
    console.error("Contract TypeScript declarations are stale.");
    process.exitCode = 1;
  }
}
